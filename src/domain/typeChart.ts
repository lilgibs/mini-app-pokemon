/** Damage multiplier of one attacking type against one defending type. */
export function effectiveness(attacker: PokemonType, defender: PokemonType): number {
  return CHART[attacker][defender] ?? 1;
}

/**
 * Damage multiplier against a whole Pokemon, whose typing may be dual.
 *
 * The multipliers multiply rather than add, which is why the extremes get so
 * far apart: Ice against a Dragon/Flying type is 4x, while Ground against a
 * Flying type is 0 no matter what its second type resists.
 */
export function effectivenessAgainst(
  attacker: PokemonType,
  defenderTypes: readonly PokemonType[]
): number {
  return defenderTypes.reduce((total, defender) => total * effectiveness(attacker, defender), 1);
}
